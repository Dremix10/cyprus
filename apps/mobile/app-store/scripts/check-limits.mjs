#!/usr/bin/env node
// Verify App Store Connect limits for every locale in ../metadata and the review notes.
//   node apps/mobile/app-store/scripts/check-limits.mjs          # prints a table, exits 1 on any failure
//   node apps/mobile/app-store/scripts/check-limits.mjs --write  # also rewrites metadata/COUNTS.md
// Counts are Unicode code points (what App Store Connect shows). Keywords also report UTF-8 bytes,
// because some sources say Apple measures the keyword field in bytes (Greek letters are 2 bytes each).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const metaDir = join(root, 'metadata');

const LIMITS = {
  'name.txt': { min: 2, max: 30 },
  'subtitle.txt': { max: 30 },
  'promotional_text.txt': { max: 170 },
  'description.txt': { min: 10, max: 4000 },
  'keywords.txt': { max: 100, keywords: true },
  'keywords_extended.txt': { max: 100, keywords: true, optional: true },
  'release_notes.txt': { max: 4000 },
  'support_url.txt': { max: 255, url: true },
  'marketing_url.txt': { max: 255, url: true, optional: true },
  'privacy_url.txt': { max: 255, url: true },
};

const chars = (s) => [...s].length;
const bytes = (s) => Buffer.byteLength(s, 'utf8');
/** Lowercase, strip accents (Τίτσου -> τιτσου), split into words. */
const words = (s) =>
  s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(Boolean);

const rows = [];
let failed = false;
const fail = (locale, file, msg) => {
  failed = true;
  rows.push({ locale, file, count: '', limit: '', status: `FAIL: ${msg}` });
};

for (const locale of readdirSync(metaDir).filter((d) => !d.includes('.')).sort()) {
  const dir = join(metaDir, locale);
  const read = (f) => (existsSync(join(dir, f)) ? readFileSync(join(dir, f), 'utf8') : null);
  const titleWords = new Set([...words(read('name.txt') ?? ''), ...words(read('subtitle.txt') ?? '')]);

  for (const [file, rule] of Object.entries(LIMITS)) {
    const text = read(file);
    if (text === null) {
      if (!rule.optional) fail(locale, file, 'missing');
      continue;
    }
    const n = chars(text);
    const problems = [];
    if (text !== text.trim()) problems.push('leading/trailing whitespace');
    if (n > rule.max) problems.push(`over ${rule.max}`);
    if (rule.min && n < rule.min) problems.push(`under ${rule.min}`);
    if (rule.url && !/^https:\/\/\S+$/.test(text)) problems.push('not an https URL');
    let extra = '';
    if (rule.keywords) {
      const list = text.split(',');
      if (/\s/.test(text)) problems.push('contains spaces');
      if (list.some((k) => !k)) problems.push('empty keyword');
      const seen = new Set();
      for (const k of list) {
        const norm = words(k).join(' ');
        if (seen.has(norm)) problems.push(`duplicate "${k}"`);
        seen.add(norm);
        for (const w of words(k)) if (titleWords.has(w)) problems.push(`"${k}" repeats a name/subtitle word`);
      }
      const b = bytes(text);
      extra = ` | ${list.length} terms, ${b} bytes${b > 100 ? ' (over 100 bytes: fine if ASC counts characters)' : ''}`;
    }
    if (problems.length) failed = true;
    rows.push({ locale, file, count: n, limit: rule.max, status: (problems.length ? `FAIL: ${problems.join('; ')}` : 'ok') + extra });
  }
}

const notesPath = join(root, 'review', 'notes.txt');
if (existsSync(notesPath)) {
  const notes = readFileSync(notesPath, 'utf8').trim();
  const n = chars(notes);
  const ok = n >= 2 && n <= 4000;
  if (!ok) failed = true;
  rows.push({ locale: 'review', file: 'notes.txt', count: n, limit: 4000, status: ok ? 'ok' : 'FAIL: length' });
}

const table = [
  '| Locale | File | Chars | Limit | Status |',
  '|---|---|---:|---:|---|',
  ...rows.map((r) => `| ${r.locale} | ${r.file} | ${r.count} | ${r.limit} | ${r.status} |`),
].join('\n');
console.log(table);
console.log(failed ? '\nSome checks FAILED.' : '\nAll limits OK.');

if (process.argv.includes('--write')) {
  const out = `# Character counts\n\nGenerated by \`node apps/mobile/app-store/scripts/check-limits.mjs --write\` on ${new Date().toISOString().slice(0, 10)}.\nRe-run it after any copy change.\n\nKeywords are checked for spaces, duplicates, and words already in the name or subtitle (accent-insensitive).\nGreek keyword note: \`el/keywords.txt\` also fits in 100 UTF-8 bytes. Try \`el/keywords_extended.txt\` first; if App Store Connect says it is too long, use \`keywords.txt\`.\n\n${table}\n`;
  writeFileSync(join(metaDir, 'COUNTS.md'), out);
  console.log('wrote metadata/COUNTS.md');
}
process.exit(failed ? 1 : 0);
